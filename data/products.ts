export const productById = new Map(products.map((product) => [product.id, product]));

export const priceBounds = {
  min: Math.min(...products.map((product) => product.price)),
  max: Math.max(...products.map((product) => product.price)),
};

export function getProductsByModel(modelId: string): Product[] {
  return products.filter(
    (product) => product.fitsUniversal || product.models.includes(modelId),
  );
}

export function getProductsByCategory(categoryId: string): Product[] {
  return products.filter((product) => product.category === categoryId);
}

export function getFeaturedProducts(limit?: number): Product[] {
  const featured = products.filter((product) => product.featured);
  const source = featured.length > 0 ? featured : products;
  return typeof limit === "number" ? source.slice(0, limit) : source;
}
